"""Export a distilled student to int8 TFLite for TFLM (per-frame windows) and check it.

    python scripts/export_tflite.py --run ds_w025

Per-frame inference: each call sees WINDOW = 40 mel frames (0.64 s), which covers the
student's 36-frame receptive field, and keeps one 64 ms output frame (TARGET = 4,
i.e. mel frames 16..19; 20 future mel frames = 0.32 s look-ahead). Windows start on a
multiple of 4 mel frames, so interior frames equal the whole-clip student exactly.

Event F1 on the validation set (whole-clip [0, 1] normalisation as before; frozen
official BiGRU; hysteresis 0.5/0.3), three ways:
  float, whole clip      the earlier `distill_cnn.py eval` setting
  float, per frame       the same weights run window by window (should match)
  int8 TFLite, per frame what TFLM would compute
Representative data for quantisation: windows from the synthetic training audio only.
Writes output/distill/<run>/{student_int8.tflite, tflite_eval.json} and the C array
firmware/tflm_probe/src/model_<run>.h for the Zephyr probe.
"""

import argparse
import json
import time

import numpy as np
import tensorflow as tf
import torch

from distill_cnn import CACHE, OUT, RELEASED, ROOT, Student, annotations, cnn_input, head, load_teacher
from lookahead_sweep import POSTPROCESSING, score

WINDOW = 40
TARGET = 4
FIRMWARE = ROOT / "firmware/tflm_probe/src"


def load_student(run):
    source = OUT / run if (OUT / run / "student.pt").exists() else RELEASED / run
    width = json.loads((source / "train.json").read_text())["args"]["width"]
    student = Student(width)
    student.load_state_dict(torch.load(source / "student.pt", map_location="cpu", weights_only=True))
    return student.eval(), width


def fold(conv, bn):
    """Fold eval-mode BatchNorm into the preceding bias-free convolution."""
    scale = bn.weight / torch.sqrt(bn.running_var + bn.eps)
    w = conv.weight * scale.reshape(-1, *([1] * (conv.weight.dim() - 1)))
    return w.detach().numpy(), (bn.bias - bn.running_mean * scale).detach().numpy()


def tf_forward(student):
    """The student as TensorFlow ops on NHWC [N, time, mel, 1] -> [N, time/4, 1, 128]."""
    w, b = fold(student.stem[0], student.stem[1])
    stem = (tf.constant(w.transpose(2, 3, 1, 0)), tf.constant(b))
    blocks = []
    for blk in student.blocks:
        dw, bn1, _, pool, pw, bn2, _ = blk
        w1, b1 = fold(dw, bn1)
        w2, b2 = fold(pw, bn2)
        size = tuple(pool.kernel_size) if isinstance(pool, torch.nn.AvgPool2d) else None
        blocks.append((tf.constant(w1.transpose(2, 3, 0, 1)), tf.constant(b1), size,
                       tf.constant(w2.transpose(2, 3, 1, 0)), tf.constant(b2)))
    proj_w = tf.constant(student.project.weight.detach().numpy()[:, :, 0].T[None, None])
    proj_b = tf.constant(student.project.bias.detach().numpy())

    def forward(x):
        x = tf.pad(x, [[0, 0], [1, 1], [1, 1], [0, 0]])            # PyTorch padding=1 on both sides
        x = tf.nn.relu(tf.nn.conv2d(x, stem[0], strides=[1, 1, 2, 1], padding="VALID") + stem[1])
        for w1, b1, size, w2, b2 in blocks:
            x = tf.nn.relu(tf.nn.depthwise_conv2d(x, w1, strides=[1, 1, 1, 1], padding="SAME") + b1)
            if size:
                x = tf.nn.avg_pool2d(x, ksize=size, strides=size, padding="VALID")
            x = tf.nn.relu(tf.nn.conv2d(x, w2, strides=1, padding="SAME") + b2)
        x = tf.reduce_mean(x, axis=2, keepdims=True)
        return tf.nn.conv2d(x, proj_w, strides=1, padding="VALID") + proj_b
    return forward


def windows(mel, frames):
    """[128, T] mel -> [frames, WINDOW, 128, 1]; window for output t starts at mel 4 * (t - TARGET)."""
    pad = np.zeros((128, 4 * TARGET + mel.shape[1] + WINDOW), np.float32)
    pad[:, 4 * TARGET:4 * TARGET + mel.shape[1]] = mel
    return np.stack([pad[:, 4 * t:4 * t + WINDOW].T for t in range(frames)])[..., None]


def representative(count, seed):
    synth = np.load(CACHE / "synthetic.npz")["mel"]
    rng = np.random.default_rng(seed)
    for _ in range(count):
        clip = synth[rng.integers(len(synth))].astype(np.float32)
        start = 4 * rng.integers(0, (clip.shape[1] - WINDOW) // 4)
        yield [clip[:, start:start + WINDOW].T[None, ..., None]]


def c_header(path, blob, name):
    rows = [", ".join(f"0x{b:02x}" for b in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    path.write_text(
        f"/* Generated by scripts/export_tflite.py: int8 TFLite student {name}, {len(blob)} bytes. */\n"
        "#pragma once\n#include <stdint.h>\n\n"
        f"alignas(16) const unsigned char g_model[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"
        f"const unsigned int g_model_len = {len(blob)};\n"
        f"#define P13_MODEL_NAME \"{name}\"\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run", required=True)
    parser.add_argument("--calibration", type=int, default=500, help="representative windows")
    parser.add_argument("--seed", type=int, default=2026)
    args = parser.parse_args()
    student, width = load_student(args.run)
    forward = tf_forward(student)

    # 1. float TensorFlow graph == PyTorch student on the same window
    probe = next(representative(1, args.seed))[0]
    with torch.inference_mode():
        ref = student(torch.from_numpy(probe.transpose(0, 3, 1, 2)).float()).numpy()  # [1, 10, 128]
    diff = float(np.abs(forward(tf.constant(probe)).numpy()[:, :, 0, :] - ref).max())
    print(f"float TF vs PyTorch on one window: max |diff| = {diff:.2e}")
    assert diff < 1e-3, "TensorFlow rebuild does not match the PyTorch student"

    # 2. int8 conversion
    fn = tf.function(forward, input_signature=[tf.TensorSpec([1, WINDOW, 128, 1], tf.float32)])
    converter = tf.lite.TFLiteConverter.from_concrete_functions([fn.get_concrete_function()], fn)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = lambda: representative(args.calibration, args.seed)
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    blob = converter.convert()
    run = OUT / args.run
    run.mkdir(parents=True, exist_ok=True)
    (run / "student_int8.tflite").write_bytes(blob)
    FIRMWARE.mkdir(parents=True, exist_ok=True)
    c_header(FIRMWARE / f"model_{args.run}.h", blob, args.run)
    interp = tf.lite.Interpreter(model_content=blob)
    ops = sorted({op["op_name"] for op in interp._get_ops_details()})
    print(f"int8 model: {len(blob):,} bytes; ops: {', '.join(ops)}")

    # 3. Event F1 on validation: whole-clip float, per-frame float, per-frame int8
    data = dict(np.load(CACHE / "validation.npz"))
    names = [str(n) for n in data["names"]]
    usable = dict(zip(names, data["usable"].tolist()))
    durations = dict(zip(names, data["durations"].tolist()))
    events = annotations()
    model, _ = load_teacher()
    outputs = {"float, whole clip": {}, "float, per frame": {}, "int8 TFLite, per frame": {}}
    start = time.time()
    for k, n in enumerate(names):
        mel = data["mel"][k, :, :data["mel_frames"][k]].astype(np.float32)
        with torch.inference_mode():
            whole = student(cnn_input(torch.from_numpy(mel)[None]))                     # [1, frames, 128]
            frames = whole.shape[1]
            x = windows(mel, frames)
            per_float = forward(tf.constant(x)).numpy()[:, TARGET, 0, :]
            inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
            interp.resize_tensor_input(inp["index"], x.shape)
            interp.allocate_tensors()
            s, z = inp["quantization"]
            interp.set_tensor(inp["index"], np.clip(np.round(x / s + z), -128, 127).astype(np.int8))
            interp.invoke()
            q = interp.get_tensor(out["index"]).astype(np.float32)
            so, zo = out["quantization"]
            per_int8 = ((q - zo) * so)[:, TARGET, 0, :]
            for key, f in (("float, whole clip", whole[0].numpy()), ("float, per frame", per_float),
                           ("int8 TFLite, per frame", per_int8)):
                outputs[key][n] = head(model, torch.from_numpy(np.ascontiguousarray(f, np.float32))[None])[0].numpy()
        if (k + 1) % 100 == 0 or k + 1 == len(names):
            print(f"validation {k + 1}/{len(names)} ({time.time() - start:.0f} s)", flush=True)

    rule = "hysteresis 0.5/0.3"
    results = {key: score(names, o, events, durations, usable, POSTPROCESSING[rule]) for key, o in outputs.items()}
    (run / "tflite_eval.json").write_text(json.dumps({
        "run": args.run, "width": width, "window_mel_frames": WINDOW, "target_frame": TARGET,
        "model_bytes": len(blob), "ops": ops, "postprocessing": rule, "recordings": len(names),
        "input_quantization": interp.get_input_details()[0]["quantization"],
        "output_quantization": interp.get_output_details()[0]["quantization"],
        "results": results}, indent=2, default=float) + "\n")
    print(f"\n{'student ' + args.run + ' | ' + rule:<40} {'frame F1':>9} {'event uF1':>10} {'event F1':>9}")
    for key, r in results.items():
        print(f"{key:<40} {r['frame_micro']['f1']:9.4f} {r['event_micro_f1']:10.4f} {r['event_macro_f1']:9.4f}")
    print(f"Saved {run / 'student_int8.tflite'}, tflite_eval.json and {FIRMWARE / f'model_{args.run}.h'}")


if __name__ == "__main__":
    main()
